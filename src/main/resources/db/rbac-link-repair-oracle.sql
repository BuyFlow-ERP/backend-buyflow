ALTER SESSION DISABLE PARALLEL DML;
ALTER SESSION DISABLE PARALLEL QUERY;

COMMIT;

INSERT INTO USER_ROLES (USER_ROLE_ID, USER_ID, ROLE_ID, CREATED_AT)
SELECT SEQ_USER_ROLES.NEXTVAL, u.USER_ID, r.ROLE_ID, SYSTIMESTAMP
FROM USERS u
JOIN ROLES r ON r.ROLE_CODE = 'ADMIN'
WHERE u.LOGIN_ID = 'admin'
  AND NOT EXISTS (
      SELECT 1
      FROM USER_ROLES ur
      WHERE ur.USER_ID = u.USER_ID
        AND ur.ROLE_ID = r.ROLE_ID
  );

COMMIT;

INSERT INTO ROLE_PERMISSIONS (ROLE_PERMISSION_ID, ROLE_ID, PERMISSION_ID, CREATED_AT)
SELECT SEQ_ROLE_PERMISSIONS.NEXTVAL, r.ROLE_ID, p.PERMISSION_ID, SYSTIMESTAMP
FROM ROLES r
CROSS JOIN PERMISSIONS p
WHERE r.ROLE_CODE = 'ADMIN'
  AND NOT EXISTS (
      SELECT 1
      FROM ROLE_PERMISSIONS rp
      WHERE rp.ROLE_ID = r.ROLE_ID
        AND rp.PERMISSION_ID = p.PERMISSION_ID
  );

COMMIT;

INSERT INTO ROLE_PERMISSIONS (ROLE_PERMISSION_ID, ROLE_ID, PERMISSION_ID, CREATED_AT)
SELECT SEQ_ROLE_PERMISSIONS.NEXTVAL, r.ROLE_ID, p.PERMISSION_ID, SYSTIMESTAMP
FROM ROLES r
JOIN PERMISSIONS p ON p.PERMISSION_CODE = 'PURCHASE_REQUEST_CREATE'
WHERE r.ROLE_CODE = 'REQUESTER'
  AND NOT EXISTS (
      SELECT 1
      FROM ROLE_PERMISSIONS rp
      WHERE rp.ROLE_ID = r.ROLE_ID
        AND rp.PERMISSION_ID = p.PERMISSION_ID
  );

COMMIT;

INSERT INTO ROLE_PERMISSIONS (ROLE_PERMISSION_ID, ROLE_ID, PERMISSION_ID, CREATED_AT)
SELECT SEQ_ROLE_PERMISSIONS.NEXTVAL, r.ROLE_ID, p.PERMISSION_ID, SYSTIMESTAMP
FROM ROLES r
JOIN PERMISSIONS p ON p.PERMISSION_CODE = 'PURCHASE_REQUEST_APPROVE'
WHERE r.ROLE_CODE = 'APPROVER'
  AND NOT EXISTS (
      SELECT 1
      FROM ROLE_PERMISSIONS rp
      WHERE rp.ROLE_ID = r.ROLE_ID
        AND rp.PERMISSION_ID = p.PERMISSION_ID
  );

COMMIT;

SELECT r.ROLE_CODE, p.PERMISSION_CODE
FROM ROLES r
JOIN ROLE_PERMISSIONS rp ON rp.ROLE_ID = r.ROLE_ID
JOIN PERMISSIONS p ON p.PERMISSION_ID = rp.PERMISSION_ID
WHERE r.ROLE_CODE IN ('ADMIN', 'REQUESTER', 'APPROVER')
ORDER BY r.ROLE_CODE, p.PERMISSION_CODE;
